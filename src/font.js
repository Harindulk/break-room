// Treat the emoji and text presentations of a heart as the same glyph.
export function normalizeText(text) {
  const lines = String(text).toUpperCase().replaceAll('❤', '♥').split('|').slice(0, 2)
    .map(line => [...line].filter(char => patterns[char]).join('').trim());
  return lines.some(line => /[^ ]/.test(line)) ? lines : ['BE RIGHT BACK'];
}

export function layoutText(text) {
  const lines = normalizeText(text);
  const columns = Math.max(...lines.map(line => line.length * 6 - 1));
  const rows = lines.length * 9 - 2;
  const cell = Math.min(46, 1680 / Math.max(1, columns), 340 / rows);
  // Reserve the top edge for the live leaderboard, even with two full lines.
  const top = 450 - rows * cell / 2;
  const pixels = [];
  lines.forEach((line, lineIndex) => {
    const left = (1920 - (line.length * 6 - 1) * cell) / 2;
    [...line].forEach((char, index) => patterns[char].split('/').slice(0, 7).forEach((row, y) => {
      [...row].forEach((pixel, x) => {
        if (pixel === '1') pixels.push({ x: left + (index * 6 + x) * cell,
          y: top + (lineIndex * 9 + y) * cell, w: cell - Math.min(4, cell * .17),
          h: cell - Math.min(4, cell * .17) });
      });
    }));
  });
  return pixels;
}
